/** t('home.fees', { fees: 'ETB 12.00' }) */
export function t(key: MsgKey, vars: Record<string, string | number> = {}): string {
  return en[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
